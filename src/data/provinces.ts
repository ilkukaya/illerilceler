export function getProvinceBySlug(slug: string): Province | undefined {
  return provinces.find((p) => p.slug === slug);
}

export function getProvinceByPlateCode(code: string): Province | undefined {
  const normalized = code.replace(/^0+/, "").padStart(2, "0");
  return provinces.find((p) => p.plateCode === normalized);
}

export function getProvinceByAreaCode(code: string): Province | undefined {
  const normalized = code.replace(/^0+/, "");
  return provinces.find((p) => p.areaCodes.some((c) => c === normalized));
}

export function getFeaturedProvinces(): Province[] {
  const slugs = [
    "istanbul",
    "ankara",
    "izmir",
    "bursa",
    "antalya",
    "konya",
    "mardin",
    "van",
    "trabzon",
    "canakkale",
    "erzurum",
    "adana",
  ];
  return slugs
    .map((s) => getProvinceBySlug(s))
    .filter((p): p is Province => Boolean(p));
}

export function getNeighborProvinces(province: Province): Province[] {
  return (province.neighbors ?? [])
    .map((slug) => getProvinceBySlug(slug))
    .filter((p): p is Province => Boolean(p));
}

export const totalDistrictCount = provinces.reduce(
  (sum, p) => sum + (p.districtCount ?? 0),
  0,
);
export const totalPopulation = provinces.reduce(
  (sum, p) => sum + (p.population ?? 0),
  0,
);
