export function getDistrictBySlug(
  provinceSlug: string,
  districtSlug: string,
): District | undefined {
  const found = districts.find(
    (d) => d.provinceSlug === provinceSlug && d.slug === districtSlug,
  );
  if (found) return found;
  const name = districtNamesByProvince[provinceSlug]?.find(
    (n) => turkishSlugify(n) === districtSlug,
  );
  if (!name) return undefined;
  return {
    id: `${provinceSlug}-${districtSlug}`,
    slug: districtSlug,
    name,
    provinceSlug,
    isDemoData: true,
  };
}

export function getDistrictsForProvince(provinceSlug: string): District[] {
  const names = districtNamesByProvince[provinceSlug];
  if (!names) return districts.filter((d) => d.provinceSlug === provinceSlug);
  return names.map((name): District => {
    const slug = turkishSlugify(name);
    const full = districts.find(
      (d) => d.provinceSlug === provinceSlug && d.slug === slug,
    );
    if (full) return full;
    return {
      id: `${provinceSlug}-${slug}`,
      slug,
      name,
      provinceSlug,
      isDemoData: true,
    };
  });
}

export function getNeighborDistricts(district: District): District[] {
  return (district.neighbors ?? [])
    .map((slug) => getDistrictBySlug(district.provinceSlug, slug))
    .filter((d): d is District => Boolean(d));
}
